from copy import deepcopy
from pathlib import Path
from docx import Document
from docx.text.paragraph import Paragraph

path = Path('docs/report/Ульянкин_ВИ_ИКБО-30-24_Учебная_практика_этап4.docx')
doc = Document(path)
anchor = next(p for p in doc.paragraphs if p.text.startswith('Отмена и перенос брони оформлены как непрерывающий'))
items = [
    'Для уточнения обмена сообщения ML5 и ML6 разделены по назначению: ML5.1 — запрос отмены, ML5.2 — запрос переноса, ML6.1 — подтверждение отмены, ML6.2 — подтверждение переноса, ML6.3 — отказ либо предложение альтернатив. Запрос клиент направляет администратору VR-арены; полученное сообщение запускает обработку в ESP1. Состояние брони и площадки проверяется по данным DS1.',
    'При отмене администратор получает ML5.1, находит активную бронь, меняет её статус на cancelled и освобождает прежний интервал. Система учёта фиксирует событие отмены в истории; клиенту направляется ML6.1. Отменённая бронь не передаётся в приём клиентов SP2, а обработка других броней продолжается.',
    'При переносе администратор получает ML5.2 и проверяет новый интервал и площадку. При доступности система обновляет бронь, фиксирует прежние и новые значения в истории и направляет клиенту ML6.2; при отказе сохраняются прежние значения и возвращается ML6.3 с причиной или альтернативами. Для успешного переноса основной процесс продолжается с актуальной бронью и новым временем; для других броней обработка не прерывается.'
]
for text in items:
    element = deepcopy(anchor._p)
    p = Paragraph(element, anchor._parent)
    p.clear()
    p.add_run(text)
    anchor._p.addnext(element)
    anchor = p
doc.save(path)
Document(path)
