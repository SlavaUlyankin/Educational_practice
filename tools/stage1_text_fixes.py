"""Точечные исправления разделов 5 и 9 рабочего отчёта."""
from pathlib import Path
from docx import Document

path = Path('docs/report/Ульянкин_ВИ_ИКБО-30-24_Учебная_практика_этап4.docx')
doc = Document(path)

def replace_once(old, new):
    matches = [run for p in doc.paragraphs for run in p.runs if old in run.text]
    if len(matches) != 1:
        raise ValueError(f'Ожидалось одно совпадение, найдено {len(matches)}: {old[:60]}')
    matches[0].text = matches[0].text.replace(old, new)

